package com.msa.compose_kmm.domain

/**
 * وضعیت‌های مختلف بازی را مشخص می‌کند.
 *
 * با استفاده از enum class می‌توان وضعیت بازی را محدود به چند مقدار مشخص کرد.
 * این کار باعث خواناتر شدن کد و کاهش خطاهای احتمالی می‌شود.
 */
enum class GameStatus {

    /**
     * حالت اولیه بازی.
     *
     * در این وضعیت بازی هنوز شروع نشده است.
     */
    Idle,

    /**
     * وضعیت اجرای بازی.
     *
     * زمانی که بازی شروع شده و منطق اصلی بازی در حال اجرا است،
     * وضعیت روی Started قرار می‌گیرد.
     */
    Started,

    /**
     * وضعیت پایان بازی.
     *
     * وقتی بازی تمام شود، مثلا در صورت برخورد یا خروج از محدوده،
     * می‌توان وضعیت بازی را روی Over قرار داد.
     */
    Over
}